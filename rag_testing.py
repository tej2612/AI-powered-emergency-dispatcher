import re
import numpy as np
from typing import List
from sentence_transformers import SentenceTransformer, util

def clean_text(text: str) -> str:
    if not isinstance(text, str) or not text:
        return ""
    # Remove URLs
    text = re.sub(r'https?://\S+|www\.\S+', ' ', text)
    # Remove twitter handles
    text = re.sub(r'@\w+', ' ', text)
    # Replace non-alphanumeric (keep spaces)
    text = re.sub(r'[^0-9A-Za-z\s]', ' ', text)
    # Normalize whitespace and lowercase
    text = re.sub(r'\s+', ' ', text).strip().lower()
    return text

class RAGEvaluator:
    """
    Improved RAG evaluator:
      - normalizes cosine similarity to [0,1]
      - semantic-based faithfulness per-sentence
      - robust keyword matching after basic cleaning
      - context embedding caching for speed
    """
    def __init__(self, embedding_model: SentenceTransformer, sem_threshold: float = 0.55):
        self.model = embedding_model
        self.sem_threshold = sem_threshold
        # small cache to avoid re-encoding same contexts repeatedly
        self._emb_cache = {}

    def _encode(self, texts: List[str]):
        """Encode list of texts into sentence-transformer tensors (with caching)."""
        # Build list of cleaned texts
        cleaned = [clean_text(t) for t in texts]
        # Create key for cache (join minimal)
        key = "||".join(cleaned)
        if key in self._emb_cache:
            return self._emb_cache[key]
        emb = self.model.encode(cleaned, convert_to_tensor=True)
        self._emb_cache[key] = emb
        return emb

    def compute_similarity(self, text1: str, text2: str) -> float:
        """
        Returns normalized cosine similarity in [0,1]
        """
        t1 = clean_text(text1)
        t2 = clean_text(text2)
        if not t1 or not t2:
            return 0.0
        emb = self.model.encode([t1, t2], convert_to_tensor=True)
        sim = util.pytorch_cos_sim(emb[0], emb[1]).item()
        # Normalize to [0,1]
        sim_norm = (sim + 1.0) / 2.0
        return float(sim_norm)

    def _keyword_score(self, context: str, expected_keywords: List[str]) -> float:
        """
        Keyword matching with relaxed checks:
        - exact word boundary match OR substring match
        - returns fraction matched in [0,1]
        """
        if not expected_keywords:
            return 0.0
        ctx = clean_text(context)
        matches = 0
        for kw in expected_keywords:
            kw_clean = clean_text(kw)
            if not kw_clean:
                continue
            # word boundary match
            if re.search(r'\b' + re.escape(kw_clean) + r'\b', ctx):
                matches += 1
            # substring fallback
            elif kw_clean in ctx:
                matches += 1
        return matches / len(expected_keywords)

    def context_precision(self, query: str, contexts: List[str], expected_keywords: List[str]) -> float:
        """
        Combined relevance score per context:
          - semantic_score (0-1)  weight 0.7
          - keyword_score (0-1)   weight 0.3
        Returns mean combined score across contexts.
        """
        if not contexts:
            return 0.0

        semantic_scores = []
        # encode all contexts at once for speed
        ctx_embs = self._encode(contexts)
        # encode query once
        q_emb = self.model.encode(clean_text(query), convert_to_tensor=True)
        for i, context in enumerate(contexts):
            # semantic similarity (use precomputed)
            try:
                c_emb = ctx_embs[i]
                sem_sim = util.pytorch_cos_sim(q_emb, c_emb).item()
                sem_sim = (sem_sim + 1.0) / 2.0
            except Exception:
                sem_sim = self.compute_similarity(query, context)
            kw_score = self._keyword_score(context, expected_keywords)
            combined = 0.7 * sem_sim + 0.3 * kw_score
            semantic_scores.append(combined)
        return float(np.mean(semantic_scores))

    def context_relevancy(self, query: str, contexts: List[str]) -> float:
        """
        Mean semantic similarity between query and each context (normalized [0,1]).
        """
        if not contexts:
            return 0.0
        ctx_embs = self._encode(contexts)
        q_emb = self.model.encode(clean_text(query), convert_to_tensor=True)
        sims = []
        for i in range(len(contexts)):
            sim = util.pytorch_cos_sim(q_emb, ctx_embs[i]).item()
            sims.append((sim + 1.0) / 2.0)
        return float(np.mean(sims))

    def faithfulness(self, response: str, contexts: List[str]) -> float:
        """
        Semantic faithfulness:
          - Split response into sentences
          - For each sentence, compute max semantic similarity to any context
          - Sentence is faithful if max_sim >= sem_threshold (default 0.55)
          - Return fraction of sentences that are faithful
        """
        if not response or not contexts:
            return 0.0
        # split sentences (lightweight)
        sentences = [s.strip() for s in re.split(r'[.!?]\s*', response) if s.strip()]
        if not sentences:
            return 0.0

        # prepare encodings
        ctx_embs = self._encode(contexts)
        faithful = 0
        for sent in sentences:
            sent_clean = clean_text(sent)
            if not sent_clean:
                continue
            sent_emb = self.model.encode(sent_clean, convert_to_tensor=True)
            # compute similarity against all contexts
            sims = util.pytorch_cos_sim(sent_emb, ctx_embs).cpu().numpy().flatten()
            sims = (sims + 1.0) / 2.0
            max_sim = float(np.max(sims))
            if max_sim >= self.sem_threshold:
                faithful += 1
            else:
                # fallback: lexical overlap (relaxed)
                sent_words = set(sent_clean.split()) - {'the','is','are','a','an','and','or','but','in','on','at','to','for','you','your','i','we','can'}
                combined_ctx = " ".join([clean_text(c) for c in contexts])
                if sent_words:
                    overlap = sum(1 for w in sent_words if re.search(r'\b' + re.escape(w) + r'\b', combined_ctx))
                    if overlap / len(sent_words) >= 0.4:
                        faithful += 1
        return float(faithful / max(1, len(sentences)))

    def answer_relevancy(self, query: str, response: str, ground_truth: str) -> float:
        """
        Combined relevancy:
          - query-response semantic (0-1)
          - response-groundtruth semantic (0-1)
          - weights: 0.7 and 0.3
        """
        if not response:
            return 0.0
        qr = self.compute_similarity(query, response)
        rg = self.compute_similarity(response, ground_truth)
        return float(0.7 * qr + 0.3 * rg)

