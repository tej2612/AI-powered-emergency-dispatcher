class RetrievalConfig:
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    TOP_K = 5
    IMAGE_BASE_PATH = "/content/drive/MyDrive/Capstone_Prototype/CrisisMMD"
    RETURN_IMAGES = False
    MAX_ITEM_CHARS = 200
    HISTORY_TURNS = 4

class RetrievalSystem:
    """Handles vector similarity search with ChromaDB"""

    def __init__(self, collection, clip_model, config):
        self.collection = collection
        self.clip_model = clip_model
        self.config = config

    def encode_text(self, query_text: str) -> List[float]:
        """Encode query text into CLIP embedding"""
        emb = self.clip_model.encode(
            [query_text],
            convert_to_tensor=True,
            device=self.config.DEVICE,
        )
        return emb[0].detach().cpu().tolist()

    def _query_chroma(self, query_embedding, n_results, where=None):
        return self.collection.query(
            query_embeddings=[query_embedding],
            n_results=n_results,
            include=["documents", "metadatas", "distances"],
            where=where or None,
        )

    def _postprocess(self, results: Dict, limit: int) -> List[Dict]:
        """Normalize Chroma results"""
        out = []
        if not results or not results.get("documents"):
            return out

        documents = (results.get("documents") or [[]])[0][:limit]
        metadatas = (results.get("metadatas") or [[]])[0][:limit]
        distances = (results.get("distances") or [[]])[0][:limit]
        ids = (results.get("ids") or [[]])[0][:limit]

        for doc, meta, distance, doc_id in zip(documents, metadatas, distances, ids):
            meta = meta or {}
            image_path_from_meta = meta.get("image_path", "")
            image_id = None
            if image_path_from_meta:
                image_filename = image_path_from_meta.split("/")[-1]
                image_id = image_filename.rsplit(".", 1)[0]

            score = 1.0 - float(distance) if distance is not None else 0.0

            out.append({
                "id": doc_id,
                "tweet_text": doc or "",
                "tweet_id": image_id.split("_")[0] if image_id else "unknown",
                "image_id": image_id,
                "disaster_type": meta.get("disaster_type", "Unknown"),
                "extracted_location": meta.get("extracted_location", ""),
                "source_file": meta.get("source_file", ""),
                "score": score,
                "image_caption": doc or "",
                "image_damage": None,
                "image_info": None,
            })
        return out

    def retrieve_topk(self, query: str, top_k: int = None) -> List[Dict]:
        """Retrieve top-k similar items from ChromaDB"""
        if top_k is None:
            top_k = self.config.TOP_K

        try:
            qvec = self.encode_text(query)
            results = self._query_chroma(qvec, n_results=top_k)
            return self._postprocess(results, top_k)
        except Exception as e:
            print(f"Error querying ChromaDB: {e}")
            return []

