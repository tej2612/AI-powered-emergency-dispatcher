import re

def infer_image_damage_and_info(retrieved_item: dict):
    """
    Extracts structured information about damage and locations from a retrieved item.

    Parameters:
        retrieved_item: A dictionary representing a single retrieved item, expected to contain 'tweet_text' and/or 'image_caption'.

    Returns:
        dict with extracted structured info about damage and locations.
    """

    # Prioritize tweet_text, fall back to image_caption
    combined_text = (retrieved_item.get("tweet_text", "") or retrieved_item.get("image_caption", "")).lower()

    damage_keywords = [
        "destroyed", "damaged", "collapsed", "flooded",
        "burnt", "washed away", "severely", "minor damage",
        "moderate damage", "heavy damage", "catastrophic", "injuries", "injured", "dead", "death", "fatalities"
    ]

    damage_level = "unknown"
    for word in damage_keywords:
        if word in combined_text:
            if word in ["minor damage"]:
                damage_level = "minor"
            elif word in ["moderate damage"]:
                damage_level = "moderate"
            elif word in ["heavy damage", "severely", "destroyed", "catastrophic", "injuries", "injured", "dead", "death", "fatalities"]:
                damage_level = "severe"
            else:
                damage_level = "damaged"
            break

    # Extract potential location names (very rough heuristic)
    # This is a basic regex, could be improved with a proper NER library.
    # Looks for capitalized words that could be part of a location name.
    location_candidates = re.findall(r"[A-Z][a-z]+(?:\s[A-Z][a-z]+)*", combined_text)
    # Filter out common non-location capitalized words or single letters, take top 3
    excluded_words = {"i", "a", "the", "and", "or", "but", "is", "in", "of", "on", "for", "with", "to", "from", "my", "we"}
    likely_locations = [loc for loc in location_candidates if len(loc) > 2 and loc.lower() not in excluded_words][:3]

    return {
        "inferred_damage_level": damage_level,
        "locations_mentioned": likely_locations,
        "supporting_evidence_snippet": combined_text[:250] + "..." if len(combined_text) > 250 else combined_text
    }

