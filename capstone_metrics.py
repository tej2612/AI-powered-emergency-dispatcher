import re, json
from typing import List, Union, Optional

class RAGASLocalLLM:
    """
    Uses a JSON-obedient model for RAGAS judging.
    - Returns LLMResult with .generations
    - Forces JSON output, and repairs schemas for:
        * statements           -> {"statements":[...]}
        * answer_relevance     -> {"question":"...", "noncommittal":bool}
        * verification         -> {"reason":"...", "verdict":bool}
        * context_recall       -> {"classifications":[...]}
    """
    def __init__(self, model, tokenizer, max_new_tokens=256, do_sample=False, name="local-eval"):
        self.model = model
        self.tok = tokenizer
        self.max_new_tokens = max_new_tokens
        self.do_sample = do_sample
        self.name = name
        if self.tok.pad_token_id is None and self.tok.eos_token_id is not None:
            self.tok.pad_token = self.tok.eos_token

    # ---------- helpers ----------
    @staticmethod
    def _coerce(prompts: Union[str, List]) -> List[str]:
        if isinstance(prompts, str): return [prompts]
        out = []
        for p in prompts:
            if isinstance(p, str): out.append(p)
            elif hasattr(p, "to_string"): out.append(p.to_string())
            elif hasattr(p, "text"): out.append(p.text)
            elif isinstance(p, dict) and "prompt" in p: out.append(str(p["prompt"]))
            else: out.append(str(p))
        return out

    @staticmethod
    def _boolish(s: str) -> Optional[bool]:
        t = s.strip().lower()
        if t in {"1","true","yes"}: return True
        if t in {"0","false","no"}: return False
        m = re.search(r"\b([01])\b", t)
        if m: return m.group(1) == "1"
        return None

    @staticmethod
    def _extract_json(text: str) -> Optional[dict]:
        text = text.strip()
        # try fenced
        m = re.search(r"```(?:json)?\s*({.*?}|\[.*?\])\s*```", text, re.DOTALL|re.IGNORECASE)
        if m:
            try: return json.loads(m.group(1))
            except: pass
        # try outermost braces
        if "{" in text and "}" in text:
            s, e = text.find("{"), text.rfind("}")
            try: return json.loads(text[s:e+1])
            except: pass
        # try full
        try: return json.loads(text)
        except: return None

    def _schema_type(self, prompt: str) -> str:
        p = prompt.lower()
        if "statements" in p and ("breakdown" in p or "extract" in p): return "statements"
        if "noncommittal" in p or "answer relevance" in p or "generate a question" in p: return "ansrel"
        if "verdict" in p or "verification" in p: return "verify"
        if "context recall" in p or "classifications" in p: return "crecall"
        if "context precision" in p: return "cprecision"
        if "question" in p: return "ansrel"
        if "statement" in p: return "statements"
        return "unknown"

    def _ensure_union(self, obj: dict) -> dict:
        if not isinstance(obj, dict): obj = {}
        obj.setdefault("statements", [])
        obj.setdefault("question", "")
        obj.setdefault("noncommittal", False)
        obj.setdefault("reason", "")
        obj.setdefault("verdict", False)
        obj.setdefault("classifications", [])
        return obj

    def _repair(self, prompt: str, obj: dict) -> dict:
        t = self._schema_type(prompt)
        obj = {} if not isinstance(obj, dict) else obj

        if t == "statements":
            v = obj.get("statements", obj.get("facts", obj.get("claims", [])))
            if isinstance(v, str): v = [v]
            if not isinstance(v, list): v = []
            return self._ensure_union({"statements": v})

        if t == "ansrel":
            q = obj.get("question", obj.get("generated_question", ""))
            nc = obj.get("noncommittal", obj.get("non_committal", False))
            if isinstance(nc, str):
                b = self._boolish(nc); nc = bool(b) if b is not None else False
            elif isinstance(nc, (int,float)): nc = bool(nc)
            elif not isinstance(nc, bool): nc = False
            return self._ensure_union({"question": str(q), "noncommittal": nc})

        if t in {"verify","cprecision"}:
            reason = obj.get("reason", obj.get("explanation",""))
            v = obj.get("verdict", obj.get("supported", False))
            if isinstance(v, str):
                b = self._boolish(v); v = bool(b) if b is not None else False
            elif isinstance(v, (int,float)): v = bool(v)
            elif not isinstance(v, bool): v = False
            return self._ensure_union({"reason": str(reason), "verdict": v})

        if t == "crecall":
            cls = obj.get("classifications", [])
            if not isinstance(cls, list): cls = [cls] if cls else []
            return self._ensure_union({"classifications": cls})

        # unknown → safe union
        return self._ensure_union(obj)

    # ---------- core ----------
    def _json_guard(self, prompt: str) -> str:
        return (prompt +
                "\n\nReturn ONLY one valid minified JSON object. "
                "No preface, no markdown, no code fences. Start with { and end with }.").strip()

    def _gen_once(self, prompts: List[str], **kwargs) -> List[str]:
        # swallow noisy kwargs
        for k in ["n","callbacks","presence_penalty","frequency_penalty",
                  "logit_bias","seed","response_format","timeout","logprobs","top_logprobs"]:
            kwargs.pop(k, None)
        temperature = kwargs.pop("temperature", None)
        top_p = kwargs.pop("top_p", None)
        max_tokens = kwargs.pop("max_tokens", None)
        max_new_tokens = kwargs.pop("max_new_tokens", self.max_new_tokens)
        do_sample = self.do_sample or (float(temperature)>0 if temperature is not None else False)

        guarded = [self._json_guard(p) for p in prompts]
        inputs = self.tok(guarded, return_tensors="pt", padding=True, truncation=True, max_length=2048).to(self.model.device)

        gen_kwargs = dict(max_new_tokens=int(max_new_tokens), do_sample=bool(do_sample),
                          pad_token_id=self.tok.eos_token_id, use_cache=True)
        if temperature is not None: gen_kwargs["temperature"] = max(0.01, float(temperature))
        if top_p is not None: gen_kwargs["top_p"] = float(top_p)
        gen_kwargs.update(kwargs)

        with torch.no_grad():
            out = self.model.generate(**inputs, **gen_kwargs)
        return self.tok.batch_decode(out, skip_special_tokens=True)

    def _to_result(self, prompts: List[str], texts: List[str]) -> LLMResult:
        gens = []
        for p, t in zip(prompts, texts):
            data = self._extract_json(t) or {}
            data = self._repair(p, data)
            gens.append([Generation(json.dumps(data, separators=(",",":")))])
        return LLMResult(generations=gens)

    # APIs RAGAS may call
    def generate(self, prompts: Union[str, List], **kwargs) -> LLMResult:
        ps = self._coerce(prompts)
        texts = self._gen_once(ps, **kwargs)
        return self._to_result(ps, texts)
    async def agenerate(self, prompts: Union[str, List], **kwargs) -> LLMResult:
        return self.generate(prompts, **kwargs)
    def generate_prompt(self, prompts: Union[str, List], **kwargs) -> LLMResult:
        return self.generate(prompts, **kwargs)
    async def agenerate_prompt(self, prompts: Union[str, List], **kwargs) -> LLMResult:
        return self.generate(prompts, **kwargs)



