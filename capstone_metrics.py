# ---------- Helpers you previously imported from utils ----------
def find_image_path(image_id: Optional[str], base_dir: str) -> Optional[str]:
    """Recursively search for an image file whose filename contains the image_id."""
    if not image_id:
        return None
    image_id = str(image_id)
    for root, _, files in os.walk(base_dir):
        for f in files:
            # quick match without extension sensitivity
            if image_id in f:
                return os.path.join(root, f)
    return None

def image_to_base64(image_path: Optional[str]) -> Optional[str]:
    """Load an image and return base64 string (PNG)."""
    if not image_path or not os.path.exists(image_path):
        return None
    try:
        with Image.open(image_path).convert("RGB") as img:
            buf = io.BytesIO()
            img.save(buf, format="PNG")
            return base64.b64encode(buf.getvalue()).decode("utf-8")
    except Exception:
        return None

def normalize_location_for_filter(loc: Optional[str]) -> Optional[str]:
    """Match your ingestion normalization (Title Case pieces, commas)."""
    if not isinstance(loc, str) or not loc.strip():
        return None
    loc = re.sub(r"[^a-zA-Z\s,]", "", loc)
    parts = [p.strip().title() for p in loc.split(",") if p.strip()]
    if not parts:
        return None
    # de-dupe preserving order
    seen = set()
    norm_parts = []
    for p in parts:
        if p not in seen:
            seen.add(p)
            norm_parts.append(p)
    return ", ".join(norm_parts)

